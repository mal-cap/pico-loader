#!/usr/bin/env python3
"""Turn the WL proxy's ELF (linked at 0 with -q) into a relocatable blob.

CLI:
    proxy_blob.py ELF --header OUT.h        # C header for Pico Loader (wlproxy/Makefile)
    proxy_blob.py ELF                       # summary

Only R_ARM_ABS32 relocations against blob-internal symbols need fixing when the
blob moves; branches are PC-relative and everything outside the blob (game
functions, queues, registers) comes in through gProxyCfg or is absolute.
"""
import struct
import sys

R_ARM_ABS32 = 2
PC_RELATIVE = {3, 28, 29, 40, 42}  # REL32, CALL, JUMP24, V4BX, PREL31: position-independent
SHN_ABS = 0xFFF1


class Blob:
    def __init__(self, data, relocs, syms):
        self.data, self.relocs, self.syms = data, relocs, syms
        self.load_size = syms["__load_end"]
        self.bss_size = syms["__bss_end"] - syms["__load_end"]
        self.cfg_off = syms["gProxyCfg"]
        if syms["proxy_WlRequest"] != 0:
            sys.exit("proxy_WlRequest must be at offset 0")


def load(path):
    elf = open(path, "rb").read()
    if elf[:4] != b"\x7fELF" or elf[4] != 1 or elf[5] != 1:
        sys.exit(f"{path}: not a 32-bit little-endian ELF")
    shoff, = struct.unpack_from("<I", elf, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<3H", elf, 0x2E)
    secs = []
    for i in range(shnum):
        name, typ, flags, addr, off, size, link, info, align, entsize = struct.unpack_from(
            "<10I", elf, shoff + i * shentsize)
        secs.append(dict(name=name, type=typ, addr=addr, off=off, size=size, link=link, info=info, entsize=entsize))
    shstr = secs[shstrndx]

    def sname(s):
        o = shstr["off"] + s["name"]
        return elf[o:elf.index(b"\0", o)].decode()

    for s in secs:
        s["n"] = sname(s)
    text = next(s for s in secs if s["n"] == ".text")
    if text["addr"] != 0:
        sys.exit(".text must be linked at 0")
    data = elf[text["off"]:text["off"] + text["size"]]

    symtab = next(s for s in secs if s["type"] == 2)
    strtab = secs[symtab["link"]]
    syms, symlist = {}, []
    for i in range(symtab["size"] // 16):
        name, value, size, info, other, shndx = struct.unpack_from("<IIIBBH", elf, symtab["off"] + i * 16)
        o = strtab["off"] + name
        n = elf[o:elf.index(b"\0", o)].decode()
        symlist.append((n, value, shndx))
        if n:
            syms[n] = value

    relocs = []
    textidx = secs.index(text)
    for s in secs:
        if s["type"] != 9 or s["info"] != textidx:   # SHT_REL for .text
            continue
        for i in range(s["size"] // 8):
            off, info = struct.unpack_from("<II", elf, s["off"] + i * 8)
            typ, symi = info & 0xFF, info >> 8
            if typ == R_ARM_ABS32:
                if symlist[symi][2] != SHN_ABS:
                    relocs.append(off)
            elif typ not in PC_RELATIVE:
                sys.exit(f"unsupported relocation type {typ} at {off:#x}")
    return Blob(data, sorted(relocs), syms)


def main():
    if len(sys.argv) not in (2, 4) or (len(sys.argv) == 4 and sys.argv[2] != "--header"):
        sys.exit(__doc__)
    b = load(sys.argv[1])
    if len(sys.argv) == 2:
        print(f"load {b.load_size:#x}, bss {b.bss_size:#x}, cfg at {b.cfg_off:#x}, {len(b.relocs)} relocations")
        return
    data = b.data[:b.load_size]
    lines = ["/* Generated by tools/proxy_blob.py from proxy.elf. Do not edit. */",
             "#pragma once", "#include <stdint.h>", "",
             f"#define WLPROXY_LOAD_SIZE 0x{b.load_size:X}u",
             f"#define WLPROXY_BSS_SIZE 0x{b.bss_size:X}u",
             f"#define WLPROXY_CFG_OFFSET 0x{b.cfg_off:X}u",
             f"#define WLPROXY_RELOC_COUNT {len(b.relocs)}u", "",
             "static const uint32_t kWlProxyBlob[] = {"]
    words = struct.unpack(f"<{len(data) // 4}I", data)
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 8]) + ",")
    if b.relocs and b.relocs[-1] > 0xFFFF:
        sys.exit("relocation offset does not fit in 16 bits")
    lines += ["};", "", "static const uint16_t kWlProxyRelocs[] = {"]
    for i in range(0, len(b.relocs), 12):
        lines.append("    " + ", ".join(f"0x{r:04X}" for r in b.relocs[i:i + 12]) + ",")
    lines += ["};", ""]
    text = "\n".join(lines)
    try:
        if open(sys.argv[3]).read() == text:
            return                          # unchanged: keep the timestamp, no rebuild
    except OSError:
        pass
    open(sys.argv[3], "w").write(text)
    print(f"wrote {sys.argv[3]}: {b.load_size:#x} bytes, bss {b.bss_size:#x}, {len(b.relocs)} relocations")


if __name__ == "__main__":
    main()
